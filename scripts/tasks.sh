    echo "Created ${MAKE_CFG_PATH} from defaults"
}

ensure_make_cfg() {
    if [[ -f "${MAKE_CFG_PATH}" ]]; then
        return
    fi

    if [[ -t 0 ]]; then
        create_make_cfg_interactive
    else
        create_make_cfg_defaults
    fi
}

load_make_cfg() {
    # shellcheck disable=SC1090
    source "${MAKE_CFG_PATH}"
}

has_command() {
    local wanted="$1"
    local cmd
    for cmd in "${commands[@]}"; do
        if [[ "${cmd}" == "${wanted}" ]]; then
            return 0
        fi
    done
    return 1
}

install_ui_dependencies() {
    local ui_dir="$1"
    local lock_file="${ui_dir}/package-lock.json"
    local node_modules_dir="${ui_dir}/node_modules"
    local hash_file="${node_modules_dir}/.camflow-lock-hash"
    local env_file="${node_modules_dir}/.camflow-node-env"
    local current_hash=""
    local stored_hash=""
    local current_env=""
    local stored_env=""

    if ! command -v npm >/dev/null 2>&1; then
        echo "npm is required but not found" >&2
        exit 1
    fi

    if [[ -f "${lock_file}" ]]; then
        if command -v sha256sum >/dev/null 2>&1; then
            current_hash="$(sha256sum "${lock_file}" | awk '{print $1}')"
        elif command -v shasum >/dev/null 2>&1; then
            current_hash="$(shasum -a 256 "${lock_file}" | awk '{print $1}')"
        fi
    fi

    current_env="$(node -p "process.platform + '-' + process.arch + '-' + process.versions.modules")"

    if [[ -f "${hash_file}" ]]; then
        stored_hash="$(cat "${hash_file}")"
    fi
    if [[ -f "${env_file}" ]]; then
        stored_env="$(cat "${env_file}")"
    fi

    if [[ -d "${node_modules_dir}" && -z "${stored_env}" ]]; then
        echo "Node module cache metadata missing; reinstalling dependencies in ${ui_dir}"
        if ! rm -rf "${node_modules_dir}" 2>/dev/null; then
            echo "Failed to remove ${node_modules_dir}" >&2
            return 75
        fi
        stored_hash=""
    fi

    if [[ -d "${node_modules_dir}" && -n "${stored_env}" && "${stored_env}" != "${current_env}" ]]; then
        echo "Node module cache environment changed (${stored_env} -> ${current_env}); reinstalling dependencies in ${ui_dir}"
        if ! rm -rf "${node_modules_dir}" 2>/dev/null; then
            echo "Failed to remove ${node_modules_dir}" >&2
            return 75
        fi
        stored_hash=""
    fi

    if [[ -d "${node_modules_dir}" && -n "${current_hash}" && "${current_hash}" == "${stored_hash}" ]]; then
        echo "Reusing React dependencies in ${ui_dir}"
        return
    fi

    echo "Installing React dependencies in ${ui_dir}"
    (
        cd "${ui_dir}"
        npm install
    )

    if [[ -n "${current_hash}" ]]; then
        mkdir -p "${node_modules_dir}"
        printf '%s\n' "${current_hash}" > "${hash_file}"
    fi
    printf '%s\n' "${current_env}" > "${env_file}"
}

sync_ui_sources_to_workdir() {
    local source_ui_dir="$1"
    local work_ui_dir="$2"

    mkdir -p "${work_ui_dir}"

    # Keep node_modules cache between runs to avoid reinstalling unchanged deps.
    find "${work_ui_dir}" -mindepth 1 -maxdepth 1 ! -name node_modules -exec rm -rf {} +

    cp "${source_ui_dir}/index.html" "${work_ui_dir}/index.html"
    cp "${source_ui_dir}/package.json" "${work_ui_dir}/package.json"
    cp "${source_ui_dir}/package-lock.json" "${work_ui_dir}/package-lock.json"
    cp "${source_ui_dir}/vite.config.js" "${work_ui_dir}/vite.config.js"
    cp -R "${source_ui_dir}/src" "${work_ui_dir}/src"
}

compute_ui_source_hash() {
    (
        cd "${PROJECT_DIR}/web"
        find index.html package.json package-lock.json vite.config.js src -type f \
            | LC_ALL=C sort | xargs sha256sum | sha256sum | awk '{print $1}'
    )
}

use_committed_ui_release() {
    local output_dir="$1"
    local release_dir="${PROJECT_DIR}/web/dist-release"
    local current_hash
    local stored_hash=""

    if [[ ! -f "${release_dir}/index.html" ]]; then
        echo "npm is required but not found, and no committed fallback exists at ${release_dir}." >&2
        echo "Run ./scripts/tasks.sh build ui-release once on a host with Node.js to create it." >&2
        exit 1
    fi

    current_hash="$(compute_ui_source_hash)"
    if [[ -f "${release_dir}/.source-hash" ]]; then
        stored_hash="$(cat "${release_dir}/.source-hash")"
    fi
    if [[ "${current_hash}" != "${stored_hash}" ]]; then
        echo "WARNING: web/dist-release is out of date with web/src (no Node.js available to rebuild it)." >&2
        echo "The embedded UI may not reflect the latest source changes." >&2
    fi

    rm -rf "${output_dir}"
    mkdir -p "$(dirname -- "${output_dir}")"
    cp -R "${release_dir}" "${output_dir}"
    echo "npm not found; used committed UI assets from ${release_dir} (Node-free build)."
}

build_web_ui() {
    local source_ui_dir="${PROJECT_DIR}/web"
    local output_dir="${1:-${UI_OUT_DIR}}"
    local work_ui_dir="${2:-${UI_WORK_DIR}}"
    local fallback_output_dir="/tmp/camflow-ui-dist"
    local fallback_work_ui_dir="/tmp/camflow-ui-work"
    local current_hash

    current_hash="$(compute_ui_source_hash)"
    if [[ -f "${output_dir}/index.html" && -f "${output_dir}/assets/app.js" && -f "${output_dir}/assets/app.css" \
          && -f "${output_dir}/.source-hash" && "$(cat "${output_dir}/.source-hash")" == "${current_hash}" ]]; then
        echo "UI assets in ${output_dir} already match web/src (unchanged); skipping rebuild."
        return
    fi

    if ! command -v npm >/dev/null 2>&1; then
        use_committed_ui_release "${output_dir}"
        return
    fi

    if [[ "${work_ui_dir}" != "${source_ui_dir}" ]]; then
        sync_ui_sources_to_workdir "${source_ui_dir}" "${work_ui_dir}"
    fi

    if ! install_ui_dependencies "${work_ui_dir}"; then
        if [[ "${work_ui_dir}" == "${source_ui_dir}" ]]; then
            echo "Warning: source UI dependencies are not writable. Falling back to ${fallback_work_ui_dir}." >&2
            echo "Hint: fix ownership of ${source_ui_dir}/node_modules to remove this warning." >&2
            work_ui_dir="${fallback_work_ui_dir}"
            sync_ui_sources_to_workdir "${source_ui_dir}" "${work_ui_dir}"
            install_ui_dependencies "${work_ui_dir}"
        else
            echo "Failed to prepare dependencies in ${work_ui_dir}" >&2
            exit 1
        fi
    fi

    if ! rm -rf "${output_dir}"; then
        if [[ "${output_dir}" == "${DEFAULT_UI_OUT_DIR}" ]]; then
            echo "Warning: could not clean ${output_dir}. Falling back to ${fallback_output_dir}." >&2
            echo "Hint: fix permissions for ${output_dir} or pass --ui-out explicitly." >&2
            output_dir="${fallback_output_dir}"
            rm -rf "${output_dir}"
        else
            echo "Failed to clean UI output directory: ${output_dir}" >&2
            echo "Hint: fix permissions or choose a different directory with --ui-out." >&2
            exit 1
        fi
    fi

    mkdir -p "$(dirname -- "${output_dir}")"
    (
        cd "${work_ui_dir}"
        CAMFLOW_WEB_OUT_DIR="${output_dir}" npm run build
    )

    if [[ ! -f "${output_dir}/index.html" ]]; then
        echo "Missing React HTML bundle: ${output_dir}/index.html" >&2
        exit 1
    fi
    if [[ ! -f "${output_dir}/assets/app.js" ]]; then
        echo "Missing React JS bundle: ${output_dir}/assets/app.js" >&2
        exit 1
    fi
    if [[ ! -f "${output_dir}/assets/app.css" ]]; then
        echo "Missing React CSS bundle: ${output_dir}/assets/app.css" >&2
        exit 1
    fi

    echo "${current_hash}" > "${output_dir}/.source-hash"
    echo "Updated embedded UI assets in ${output_dir}"
}

freeze_ui_release_action() {
    local release_dir="${PROJECT_DIR}/web/dist-release"
    local tmp_out="/tmp/camflow-ui-release-build"
    local tmp_work="/tmp/camflow-ui-release-work"

    if ! command -v npm >/dev/null 2>&1; then
        echo "npm is required to freeze UI release assets." >&2
        exit 1
    fi

    build_web_ui "${tmp_out}" "${tmp_work}"

    rm -rf "${release_dir}"
    mkdir -p "${release_dir}"
    cp -R "${tmp_out}/." "${release_dir}/"
    compute_ui_source_hash > "${release_dir}/.source-hash"
    echo "Updated committed UI assets in ${release_dir}"
}

build_runtime_dev() {
    local arch
    local build_dir
    local cache_file
    local generator
    local active_generator
    local configure_args=()
    local opencv_dir
    local opencv_build_dir
    local opencv_install_script

    arch="$(host_arch)"
    build_dir="${PROJECT_DIR}/build-runtime"
    cache_file="${build_dir}/CMakeCache.txt"
    generator="Ninja"
    active_generator=""
    opencv_dir="${OPENCV_DIR:-${PROJECT_DIR}/opencv/${OPENCV_VERSION}/linux-${arch}}"
    opencv_build_dir="${OPENCV_BUILD_DIR:-${PROJECT_DIR}/opencv/${OPENCV_VERSION}/build-linux-${arch}}"
    opencv_install_script="${PROJECT_DIR}/.github/scripts/install-opencv-${OPENCV_VERSION}.sh"

    if [[ ! -x "${opencv_install_script}" ]]; then
        echo "Unsupported OpenCV version ${OPENCV_VERSION}: missing ${opencv_install_script}" >&2
        exit 1
    fi

    CAMFLOW_SKIP_APT=1 "${opencv_install_script}" "${opencv_dir}" "${opencv_build_dir}"

    if [[ -f "${cache_file}" ]]; then
        active_generator="$(sed -n 's/^CMAKE_GENERATOR:INTERNAL=//p' "${cache_file}" | head -n 1)"
    fi

    if [[ -z "${active_generator}" ]]; then
        if command -v ninja >/dev/null 2>&1; then
            configure_args+=("-G" "${generator}")
            echo "Configuring local runtime build with generator: ${generator}"
        else
            echo "Ninja not found; falling back to CMake default generator"
        fi
    else
        echo "Reusing existing local runtime generator: ${active_generator}"
    fi

    configure_args+=(
        -S "${PROJECT_DIR}"
        -B "${build_dir}"
        -DBUILD_RUNTIME=ON
        -DCMAKE_BUILD_TYPE="${BUILD_TYPE}"
        -DOpenCV_DIR="${opencv_dir}/lib/cmake/opencv4"
    )

    if command -v ccache >/dev/null 2>&1; then
        configure_args+=(
            -DCMAKE_C_COMPILER_LAUNCHER=ccache
            -DCMAKE_CXX_COMPILER_LAUNCHER=ccache
        )
        echo "Enabled compiler cache: ccache"
    fi

    cmake "${configure_args[@]}"
    cmake --build "${build_dir}" --parallel
}

build_runtime_arm64() {
    local image_name
    local build_dir
    local rebuild_image
    local opencv_dir
    local opencv_build_dir
    local opencv_install_script
    local arm64_ui_out_dir
    local arm64_ui_work_dir
    local arm64_ccache_dir

    image_name="${IMAGE_NAME:-${DEFAULT_ARM64_IMAGE}}"
    build_dir="${ARM64_BUILD_DIR:-${DEFAULT_ARM64_BUILD_DIR}}"
    rebuild_image="${ARM64_REBUILD_IMAGE:-${DEFAULT_ARM64_REBUILD_IMAGE}}"
    opencv_dir="${OPENCV_DIR:-opencv/${OPENCV_VERSION}/linux-arm64}"
    opencv_build_dir="${OPENCV_BUILD_DIR:-opencv/${OPENCV_VERSION}/build-linux-arm64}"
    opencv_install_script="${PROJECT_DIR}/.github/scripts/install-opencv-${OPENCV_VERSION}.sh"
    arm64_ui_out_dir="${PROJECT_DIR}/${build_dir}/web-dist"
    arm64_ui_work_dir="${PROJECT_DIR}/${build_dir}/web-build"
    arm64_ccache_dir="${PROJECT_DIR}/.ccache-arm64"

    if [[ ! -x "${opencv_install_script}" ]]; then
        echo "Unsupported OpenCV version ${OPENCV_VERSION}: missing ${opencv_install_script}" >&2
        exit 1
    fi

    # Pre-build the web UI on the host (current Node) so the arm64 container,
    # which only has the C++ toolchain, finds up-to-date assets and skips npm.
    echo "Building web UI assets on host for arm64 embed: ${arm64_ui_out_dir}"
    build_web_ui "${arm64_ui_out_dir}" "${arm64_ui_work_dir}"
    mkdir -p "${arm64_ccache_dir}"

    local dockerfile_hash
    local image_dockerfile_hash=""
    dockerfile_hash="$(sha256sum "${PROJECT_DIR}/docker/ubuntu-arm64/Dockerfile" | awk '{print $1}')"
    if docker image inspect "${image_name}" >/dev/null 2>&1; then
        image_dockerfile_hash="$(docker image inspect "${image_name}" --format '{{index .Config.Labels "camflow.dockerfile-hash"}}' 2>/dev/null || true)"
    fi

    if [[ "${rebuild_image}" == "1" || -z "${image_dockerfile_hash}" || "${image_dockerfile_hash}" != "${dockerfile_hash}" ]]; then
        echo "Building ARM64 Docker image: ${image_name}"
        docker build --platform linux/arm64 \
            --label "camflow.dockerfile-hash=${dockerfile_hash}" \
            -t "${image_name}" \
            "${PROJECT_DIR}/docker/ubuntu-arm64"
    else
        echo "Reusing ARM64 Docker image: ${image_name}"
    fi

    docker run --rm --platform linux/arm64 \
        --user "$(id -u):$(id -g)" \
        -e HOME=/tmp \
        -e CCACHE_DIR=/ccache \
        -v "${PROJECT_DIR}:/workspace" \
        -v "${arm64_ccache_dir}:/ccache" \
        -w /workspace \
        "${image_name}" \
        bash -lc "git config --global --add safe.directory /workspace && ccache --set-config=max_size=5G && CAMFLOW_SKIP_APT=1 ./.github/scripts/install-opencv-${OPENCV_VERSION}.sh /workspace/${opencv_dir} /workspace/${opencv_build_dir} && ccache_flags='-DCMAKE_C_COMPILER_LAUNCHER=ccache -DCMAKE_CXX_COMPILER_LAUNCHER=ccache' && echo 'Enabled persistent ccache: \${CCACHE_DIR} (size limit: 5G)' && cmake -B ${build_dir} -G Ninja -DCMAKE_BUILD_TYPE=${BUILD_TYPE} -DBUILD_RUNTIME=ON -DOpenCV_DIR=/workspace/${opencv_dir}/lib/cmake/opencv4 \${ccache_flags} && cmake --build ${build_dir} --parallel"
}

deploy_runtime_arm64() {
    local target_spec="${USER}@${TARGET}"
    local ssh_opts=(
        -o BatchMode=yes
        -o StrictHostKeyChecking=accept-new
        -o ConnectTimeout=8
        -o ConnectionAttempts=1
        -o ServerAliveInterval=5
        -o ServerAliveCountMax=2
        -n
    )
    local scp_opts=(
        -o BatchMode=yes
        -o StrictHostKeyChecking=accept-new
        -o ConnectTimeout=8
        -o ConnectionAttempts=1
        -o ServerAliveInterval=5
        -o ServerAliveCountMax=2
    )
    local build_dir="${ARM64_BUILD_DIR:-${DEFAULT_ARM64_BUILD_DIR}}"
    local binary_path="${PROJECT_DIR}/${build_dir}/camflow"
    local legacy_binary_path="${PROJECT_DIR}/${build_dir}/src/runtime/camflow"
    local resolved_binary_path="${binary_path}"

    if [[ ! -f "${resolved_binary_path}" && -f "${legacy_binary_path}" ]]; then
        resolved_binary_path="${legacy_binary_path}"
    fi

    if [[ ! -f "${resolved_binary_path}" ]]; then
        echo "Binary not found: ${resolved_binary_path}" >&2
        echo "Build first: ./scripts/tasks.sh build arm64 runtime" >&2
        exit 1
    fi

    echo "Creating target directory ${TARGET_DIR} on ${target_spec}"
    ssh "${ssh_opts[@]}" "${target_spec}" "mkdir -p '${TARGET_DIR}'"

    echo "Checking running camflow on ${target_spec}"
    if ssh "${ssh_opts[@]}" "${target_spec}" "command -v pgrep >/dev/null && pgrep -x camflow >/dev/null"; then
        echo "Stopping running camflow on ${target_spec}"
        ssh "${ssh_opts[@]}" "${target_spec}" "if command -v pkill >/dev/null 2>&1; then pkill -x camflow || true; elif command -v pgrep >/dev/null 2>&1; then for pid in \$(pgrep -x camflow || true); do kill \"\$pid\" || true; done; fi"

        local stopped=false
        local i
        for ((i = 0; i < 10; ++i)); do
            if ! ssh "${ssh_opts[@]}" "${target_spec}" "command -v pgrep >/dev/null && pgrep -x camflow >/dev/null"; then
                stopped=true
                break
            fi
            sleep 0.1
        done

        if [[ "${stopped}" != "true" ]]; then
            echo "Failed to stop running camflow on ${target_spec}" >&2
            exit 1
        fi
    else
        echo "No running camflow process found on ${target_spec}"
    fi

    local remote_tmp_path="/tmp/camflow.deploy.$$"

    echo "Copying binary to ${target_spec}:${remote_tmp_path}"
    scp "${scp_opts[@]}" "${resolved_binary_path}" "${target_spec}:${remote_tmp_path}"

    echo "Installing binary to ${target_spec}:${TARGET_DIR}/camflow"
    ssh "${ssh_opts[@]}" "${target_spec}" "chmod +x '${remote_tmp_path}' && mv -f '${remote_tmp_path}' '${TARGET_DIR}/camflow'"

    echo "Deploy finished: ${target_spec}:${TARGET_DIR}/camflow"
}

run_runtime_dev() {
    local tail_log="${1:-${TAIL_LOG}}"
    local binary_path="${PROJECT_DIR}/build-runtime/camflow"
    local runtime_args=(--verbose "${VERBOSE_LEVEL}" --port "${PORT}")

    if [[ ! -f "${binary_path}" ]]; then
        echo "Binary not found: ${binary_path}" >&2
        echo "Build first: ./scripts/tasks.sh build dev runtime" >&2
        exit 1
    fi

    pkill -x camflow || true
    chmod +x "${binary_path}"
    if [[ -n "${LOCAL_DEVICE}" ]]; then
        runtime_args+=(--device "${LOCAL_DEVICE}")
    fi
    if [[ -n "${LOCAL_SUBDEVICES}" ]]; then
        runtime_args+=(--subdevices "${LOCAL_SUBDEVICES}")
    fi
    nohup "${binary_path}" "${runtime_args[@]}" >"${LOG_PATH}" 2>&1 </dev/null &

    echo "Local camflow started: http://127.0.0.1:${PORT}"
    echo "Local log: ${LOG_PATH}"

    if [[ "${tail_log}" == "1" ]]; then
        tail -n +1 -f "${LOG_PATH}"
    fi
}

run_runtime_arm64() {
    local tail_log="${1:-${TAIL_LOG}}"
    local stop_existing="${2:-1}"
    local target_spec="${USER}@${TARGET}"
    local remote_log="/tmp/camflow-ui.log"
    local runtime_args="--verbose '${VERBOSE_LEVEL}' --port '${PORT}'"
    local ssh_opts=(
        -o BatchMode=yes
        -o ConnectTimeout=8
        -o ConnectionAttempts=1
        -o ServerAliveInterval=5
        -o ServerAliveCountMax=2
        -n
    )

    if [[ "${stop_existing}" == "1" ]]; then
        echo "Stopping running camflow on ${target_spec} (if active)"
        ssh "${ssh_opts[@]}" "${target_spec}" "if command -v pkill >/dev/null 2>&1; then pkill -x camflow || true; elif command -v pgrep >/dev/null 2>&1; then for pid in \$(pgrep -x camflow || true); do kill \"\$pid\" || true; done; fi"
    else
        echo "Skipping runtime stop: deploy already stopped camflow on ${target_spec}"
    fi

    if [[ -n "${REMOTE_DEVICE}" ]]; then
        runtime_args+=" --device '${REMOTE_DEVICE}'"
    fi
    if [[ -n "${REMOTE_SUBDEVICES}" ]]; then
        runtime_args+=" --subdevices '${REMOTE_SUBDEVICES}'"
    fi

    echo "Starting camflow UI mode on ${target_spec}:${PORT}"
    ssh "${ssh_opts[@]}" "${target_spec}" "chmod +x '${TARGET_DIR}/camflow' && : > '${remote_log}' && if command -v setsid >/dev/null 2>&1; then setsid '${TARGET_DIR}/camflow' ${runtime_args} >'${remote_log}' 2>&1 < /dev/null & else nohup '${TARGET_DIR}/camflow' ${runtime_args} >'${remote_log}' 2>&1 </dev/null & fi"

    echo "UI started: http://${TARGET}:${PORT}"
    if [[ "${tail_log}" == "1" ]]; then
        echo "Streaming remote camflow log from ${target_spec} (Ctrl-C detaches, camflow keeps running)"
        ssh "${ssh_opts[@]}" "${target_spec}" "tail -n +1 -f '${remote_log}'"
    else
        echo "Remote log tail disabled (TAIL_LOG=${tail_log})"
        echo "Inspect log manually: ssh ${target_spec} tail -f '${remote_log}'"
    fi
}

run_ui_dev() {
    local ui_dir="${PROJECT_DIR}/web"
    local api_target="http://127.0.0.1:${UI_API_PORT}"
    local ws_target="ws://127.0.0.1:${UI_API_PORT}"

    install_ui_dependencies "${ui_dir}"

    echo "UI dev server (HMR): http://127.0.0.1:${UI_DEV_PORT}"
    echo "Proxy target: ${api_target}"
    echo "Direct WS target: ${ws_target}"

    (
        cd "${ui_dir}"
        CAMFLOW_WEB_DEV_PORT="${UI_DEV_PORT}" \
        CAMFLOW_WEB_API_TARGET="${api_target}" \
        VITE_CAMFLOW_WS_TARGET="${ws_target}" \
        npm run dev -- --host 0.0.0.0 --strictPort
    )
}

start_ui_dev_background() {
    local ui_dir="${PROJECT_DIR}/web"
    local api_target="http://127.0.0.1:${UI_API_PORT}"
    local ws_target="ws://127.0.0.1:${UI_API_PORT}"
    local ui_log_path="/tmp/camflow-ui-dev.log"

    install_ui_dependencies "${ui_dir}"

    nohup bash -lc "cd '${ui_dir}' && CAMFLOW_WEB_DEV_PORT='${UI_DEV_PORT}' CAMFLOW_WEB_API_TARGET='${api_target}' VITE_CAMFLOW_WS_TARGET='${ws_target}' npm run dev -- --host 0.0.0.0 --strictPort" >"${ui_log_path}" 2>&1 </dev/null &
    echo "UI dev server started in background: http://127.0.0.1:${UI_DEV_PORT}"
    echo "UI dev log: ${ui_log_path}"
}

install_host_dependencies() {
    local apt_prefix=""

    if [[ "${OSTYPE}" != linux* ]]; then
        echo "Unsupported operating system: ${OSTYPE}" >&2
        exit 1
    fi

    if command -v sudo >/dev/null 2>&1; then
        apt_prefix="sudo"
    fi

    ${apt_prefix} apt-get update
    ${apt_prefix} apt-get install -y \
        build-essential \
        cmake \
        ninja-build \
        git \
        pkg-config \
        curl \
        ca-certificates \
        nodejs \
        libeigen3-dev \
        libjpeg-dev \
        libpng-dev \
        libtiff-dev \
        libwebp-dev \
        clang-format-15 \
        python3 \
        python3-numpy \
        doxygen \
        graphviz

    if ! command -v node >/dev/null 2>&1; then
        echo "node is missing after dependency install" >&2
        exit 1
    fi

    if ! command -v npm >/dev/null 2>&1; then
        echo "npm is missing after dependency install." >&2
        echo "Install npm from your Node.js distribution (for example NodeSource nodejs includes npm)." >&2
        exit 1
    fi
}

install_project_opencv() {
    local arch
    local install_script

    arch="$(host_arch)"
    install_script="${PROJECT_DIR}/.github/scripts/install-opencv-${OPENCV_VERSION}.sh"

    if [[ ! -x "${install_script}" ]]; then
        echo "OpenCV installer not found for version ${OPENCV_VERSION}: ${install_script}" >&2
        exit 1
    fi

    "${install_script}" \
        "${PROJECT_DIR}/opencv/${OPENCV_VERSION}/linux-${arch}" \
        "${PROJECT_DIR}/opencv/${OPENCV_VERSION}/build-linux-${arch}"
}

install_dependencies_action() {
