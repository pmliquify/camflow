Commands:
  build          Build the selected products.
  deploy         Deploy the runtime binary to the ARM64 target.
  run            Run the selected runtime(s).
    deps           Install host dependencies and project-local OpenCV package.
    format         Format C/C++ sources using clang-format.
    docs           Generate Doxygen API documentation.
    ui-release     Rebuild web/dist-release from web/src (requires Node.js); commit the result so
                   Node-free hosts can embed the UI without npm.

Platforms:
  dev            Native Linux development build/run.
  arm64          ARM64 cross build/deploy/run.

Products:
  runtime        C++ runtime binary.
  ui             React UI bundle.

Options:
  --ip HOST      Target host/IP for ARM64 deployment and remote UI.
  --dir DIR      Target directory on the ARM64 host.
  --port PORT    UI port for local and remote runtime runs.
    --tail-log 0|1 Override runtime log tailing behavior for run commands.
    --log-path PATH
                                Override runtime log output path (use /dev/null to disable file logging).
  --user USER    SSH user for ARM64 deployment and remote UI.
  --opencv VER   OpenCV version folder name.
    --rebuild-image 0|1
                                                                Force rebuild of ARM64 Docker image before cross-build.
  --ui-out DIR   UI build output directory (used by CMake integration).
