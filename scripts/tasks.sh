    --output DIR   Docs output directory for the docs action.
    --install-deps Install documentation dependencies for the docs action.
  --help         Show this help text.

Examples:
    ./scripts/tasks.sh build
    ./scripts/tasks.sh build deploy run arm64 runtime --ip 192.168.1.10
    ./scripts/tasks.sh build ui dev
    ./scripts/tasks.sh run dev ui --ui-port 8081 --api-port 8000
    ./scripts/tasks.sh run dev runtime ui --port 8000 --ui-port 8081 --api-port 8000
    ./scripts/tasks.sh build dev ui --ui-out build-runtime/web-dist --ui-work build-runtime/web-build
    ./scripts/tasks.sh deps --opencv 4.12.0
    ./scripts/tasks.sh format --clang-format clang-format-15
    ./scripts/tasks.sh docs --clean --install-deps
    ./scripts/tasks.sh ui-release
