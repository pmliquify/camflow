#!/usr/bin/env bash
# Unified camflow task entry point.
#
# If scripts/tasks.cfg is missing, this script creates it. In interactive terminals it
# asks for all values first; in non-interactive runs it writes defaults.

set -euo pipefail

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
PROJECT_DIR=$(cd -- "${SCRIPT_DIR}/.." && pwd)
MAKE_CFG_PATH="${SCRIPT_DIR}/tasks.cfg"

DEFAULT_BUILD_TYPE=Debug
DEFAULT_TARGET=imx8mp-var-dart
DEFAULT_TARGET_DIR=/usr/bin
DEFAULT_PORT=8000
DEFAULT_USER=root
DEFAULT_OPENCV_VERSION=4.12.0
DEFAULT_LOCAL_DEVICE=
DEFAULT_LOCAL_SUBDEVICES=
DEFAULT_REMOTE_DEVICE=
DEFAULT_REMOTE_SUBDEVICES=
DEFAULT_TAIL_LOG=1
DEFAULT_VERBOSE_LEVEL=3
DEFAULT_LOG_PATH=/tmp/camflow-local-ui.log
DEFAULT_UI_OUT_DIR="${PROJECT_DIR}/web/dist"
DEFAULT_UI_WORK_DIR="${PROJECT_DIR}/web"
DEFAULT_UI_DEV_PORT=8081
DEFAULT_UI_API_PORT=8000
DEFAULT_ARM64_BUILD_DIR=build-runtime-arm64
DEFAULT_ARM64_IMAGE=camflow-arm64
DEFAULT_ARM64_REBUILD_IMAGE=0

print_help() {
