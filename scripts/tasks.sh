    echo "Dependencies installed successfully"
}

format_sources_action() {
    local clang_format_bin="${CLANG_FORMAT_BIN}"

    find "${PROJECT_DIR}/src" -type f \
        \( -name '*.cpp' -o -name '*.hpp' -o -name '*.c' -o -name '*.h' -o -name '*.cc' \) \
        -print0 | xargs -0 "${clang_format_bin}" -i
}

install_doc_dependencies_action() {
    if [[ "${OSTYPE}" == "linux-gnu"* ]]; then
        if command -v sudo >/dev/null 2>&1; then
            sudo apt update >/dev/null 2>&1 || true
            sudo apt install -y doxygen graphviz curl >/dev/null
        else
            apt-get update >/dev/null 2>&1 || true
            apt-get install -y doxygen graphviz curl >/dev/null
        fi
    elif [[ "${OSTYPE}" == "darwin"* ]]; then
        if ! command -v brew >/dev/null; then
            echo "Error: Homebrew is required on macOS." >&2
            exit 1
        fi
        brew install doxygen graphviz curl >/dev/null
    else
        echo "Unsupported operating system: ${OSTYPE}" >&2
        echo "Install manually: doxygen graphviz curl" >&2
        exit 1
    fi
}

